def _hermite(logs: list[float], deriv, eta: float) -> float:
    """굳혀 둔 격자 위의 3차 Hermite 보간. **ln F 를 보간한다.**

    기울기는 d(ln F_j)/dη = j·F_{j−1}/F_j 라는 항등식에서 오므로 정확하고, 그래서 격자가
    성기어도 4차로 수렴한다. 값을 그대로 보간하면 같은 격자에서 오차가 여덟 배 커진다."""
    i = int((eta - ETA_LO) / ETA_STEP)
    if i < 0:
        i = 0
    elif i > len(logs) - 2:
        i = len(logs) - 2
    x0 = ETA_LO + i * ETA_STEP
    t = (eta - x0) / ETA_STEP
    y0, y1 = logs[i], logs[i + 1]
    d0, d1 = deriv(i), deriv(i + 1)
    t2, t3 = t * t, t * t * t
    return math.exp((2 * t3 - 3 * t2 + 1) * y0 + (t3 - 2 * t2 + t) * ETA_STEP * d0
                    + (-2 * t3 + 3 * t2) * y1 + (t3 - t2) * ETA_STEP * d1)


def _series(j: float, eta: float) -> float:
    """η ≤ −1 의 폴리로그 급수. 근사가 아니라 수렴한 급수다."""
    total = 0.0
    for k in range(1, 41):
        term = ((-1) ** (k + 1)) * math.exp(k * eta) / k ** (j + 1.0)
        total += term
        if abs(term) < 1e-18 * abs(total):
            break
    return math.gamma(j + 1.0) * total


def _sommerfeld(j: float, eta: float) -> float:
    """η ≥ 15 의 축퇴 전개. η=15 에서 1.3e-7 이고 위로 갈수록 좋아진다."""
    a = (j + 1) * j * math.pi ** 2 / 6.0
    b = (j + 1) * j * (j - 1) * (j - 2) * 7.0 * math.pi ** 4 / 360.0
    c = ((j + 1) * j * (j - 1) * (j - 2) * (j - 3) * (j - 4)
         * 31.0 * math.pi ** 6 / 15120.0)
    e2 = eta * eta
    return eta ** (j + 1) / (j + 1) * (1.0 + a / e2 + b / e2 ** 2 + c / e2 ** 3)


# ln F 와 그 정확한 기울기. 굳혀 둔 값에서 나오므로 새 상수가 아니다.
_LN_M12 = [math.log(v) for v in FD_M12]
_LN_P12 = [math.log(v) for v in FD_P12]
_LN_P32 = [math.log(v) for v in FD_P32]
# d(ln F_j)/dη = j·F_{j−1}/F_j. j = 1/2 와 3/2 는 표 안에서 닫힌다.
_D_P12 = [0.5 * FD_M12[i] / FD_P12[i] for i in range(len(FD_P12))]
_D_P32 = [1.5 * FD_P12[i] / FD_P32[i] for i in range(len(FD_P32))]
# F_{−1/2} 의 기울기는 F_{−3/2} 를 요구하는데 이 파일에 없다. 격자 위 중앙차분으로 둔다 —
# 이 함수는 Newton 의 기울기 공급용이라 값 자체보다 한 자리 낮아도 왕복이 닫히고,
# 아래 역함수 검사가 그것을 재서 보인다.
_D_M12 = [(_LN_M12[min(i + 1, len(_LN_M12) - 1)] - _LN_M12[max(i - 1, 0)])
          / (ETA_STEP * (min(i + 1, len(_LN_M12) - 1) - max(i - 1, 0)))
          for i in range(len(_LN_M12))]


def f_minus_half(eta: float) -> float:
    """F_{−1/2}(η). f_half 의 도함수가 이걸 먹는다."""
    if eta <= ETA_LO:
        return _series(-0.5, eta)
    if eta >= ETA_HI:
        return _sommerfeld(-0.5, eta)
    return _hermite(_LN_M12, lambda i: _D_M12[i], eta)


def f_half(eta: float) -> float:
    """F_{1/2}(η)."""
    if eta <= ETA_LO:
        return _series(0.5, eta)
    if eta >= ETA_HI:
        return _sommerfeld(0.5, eta)
    return _hermite(_LN_P12, lambda i: _D_P12[i], eta)


def f_three_half(eta: float) -> float:
    """F_{3/2}(η)."""
    if eta <= ETA_LO:
        return _series(1.5, eta)
    if eta >= ETA_HI:
        return _sommerfeld(1.5, eta)
    return _hermite(_LN_P32, lambda i: _D_P32[i], eta)


_LAST_INVERSE = (0.0, 0.0)     # 직전 (값, 해). 출발점일 뿐이다


def inverse_f_half(value: float) -> float:
    """F_{1/2}(η) = value 를 푸는 η. 단조증가라 뿌리가 하나다.

    도함수가 (1/2)F_{−1/2} 로 닫혀 있으므로 Newton 이 두세 번에 붙는다. 괄호를 벗어나면
    이분법으로 되돌린다 — 적분 안쪽 고리라 반복 횟수가 곧 실행시간이다."""
    if value <= 0.0:
        raise ValueError(f"F_1/2 의 역함수에 양수가 아닌 값 {value}")
    # 첫 추측. 적분기가 매끄럽게 행진하므로 **직전 해** 가 대개 제일 가깝다 — 그게
    # 빗나가도 아래 괄호가 잡아 주고, 맞으면 Newton 이 두 번에 붙는다. 캐시가 아니라
    # 출발점이므로 답에는 들어가지 않는다.
    global _LAST_INVERSE
    prev_v, prev_eta = _LAST_INVERSE
    if prev_v > 0.0 and 0.2 < value / prev_v < 5.0:
        eta = prev_eta
    elif value < 0.5:
        eta = math.log(value / math.gamma(1.5))
    else:
        eta = (1.5 * value) ** (2.0 / 3.0)
    lo, hi = -800.0, 1.0e4
    for _ in range(60):
        f = f_half(eta) - value
        if f > 0.0:
            hi = min(hi, eta)
        else:
            lo = max(lo, eta)
        if abs(f) <= 1e-13 * value:
            _LAST_INVERSE = (value, eta)
            return eta
        step = f / (0.5 * f_minus_half(eta))
        nxt = eta - step
        if not (lo < nxt < hi):
            nxt = 0.5 * (lo + hi)
        if abs(nxt - eta) <= 1e-14 * max(abs(eta), 1.0):
            _LAST_INVERSE = (value, nxt)
            return nxt
        eta = nxt
    _LAST_INVERSE = (value, eta)
    return eta
