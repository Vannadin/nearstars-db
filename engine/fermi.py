# 페르미-디랙 적분 F_j(η) — Padé 표가 아니라 정의 그대로. eos.py 의 뜨거운 물이 이걸 먹는다
"""Fermi-Dirac integrals, from the definition rather than from a fitted table.

    from fermi import f_half, f_three_half, inverse_f_half

    f_half(0.0)          → 0.678093895153...     (F_{1/2}(0))
    inverse_f_half(x)    → η 로, f_half(η) = x

**왜 이 파일이 있나.** Mazevet+ 2019 의 뜨거운 물 상태방정식이 이상 전자 페르미 기체의
자유에너지를 먹고, 그게 F_{1/2}·F_{3/2} 와 F_{1/2} 의 역함수를 요구한다. 그들의 참조
구현(eoswater21.f)은 Antia 1993 의 Padé 근사로 그것을 계산하는데, 계수표가 270개쯤이고
전부 물과 무관한 수치 라이브러리다. **그 표는 정본이 아니라 1993년 포트란용 근사다.**
정본은 정의다.

    F_j(η) = ∫₀^∞ x^j / (exp(x − η) + 1) dx

그래서 여기서는 정의를 쓴다. 세 구간으로 갈리고, 두 구간은 **표가 아니라 급수** 다.

* η ≤ −1 — 폴리로그 급수. F_j = Γ(j+1) Σ_{k≥1} (−1)^{k+1} e^{kη}/k^{j+1} 이고, η ≤ −1
  에서 40항이면 기계정밀도다(측정: 상대오차 ~1e-16). 근사가 아니라 수렴한 급수다.
* −1 < η < 20 — **굳혀 둔 표** 를 Hermite 로 보간한다. 값이 여러 자릿수를 지나므로
  ln F 를 보간하고, 기울기는 항등식 d(ln F_j)/dη = j·F_{j−1}/F_j 에서 정확히 온다.
  선형 공간에서 보간하면 같은 격자로 3.9e-6 이 나온다 — 재보고 로그 공간으로 옮겼다.
* η ≥ 20 — Sommerfeld 축퇴 전개. η=20 에서 상대오차 1.1e-8 이고 위로 갈수록
  좋아진다. 이음매를 15 가 아니라 20 에 둔 것은 재보고 옮긴 것이다 — 15 에서는
  이음매 도약이 1.3e-7 이라 역함수의 왕복 오차를 그 자리에서 지배했다.

**표가 새 오차원이다. 얼음 III·V·VI 선례와 다른 점이 그것이다.** 그때 굳힌 것은 상수
셋이었고 여기서는 함수의 표라서, 굳힌 값이 맞는지와 별개로 **보간 오차** 가 생긴다.
그래서 그 수를 재서 적는다 — 아래 INTERP_WORST 이고, test_fermi.py 가 다시 잰다.

**굳힌 값의 출처와 검증.** 표는 개발 venv 에서 scipy.integrate.quad 로 위 정적분을
평가한 값이다. 검증은 **독립된 두 번째 오라클** 로 한다 — 폴리로그 항등식
F_j(η) = −Γ(j+1)·Li_{j+1}(−e^η) 를 mpmath 40자리로 평가한 값이고, 두 방법이
η ∈ [−5, 1000] · j = 1/2·3/2 전 구간에서 최악 2.5e-10 으로 일치한다. 방법 둘을 교차시키는
것은 이 저장소의 검증 규율 그대로다. scipy 가 없으면 test_fermi.py 의 그 절이 SKIP 하고,
scripts/check.sh 는 시스템 파이썬에 의존성 없이 돈다.

**역함수에는 표가 따로 없다.** F_{1/2} 는 단조증가이고 도함수가 닫힌 형태로 있으므로
(dF_j/dη = j·F_{j−1}), 순방향 표 위에 Newton 을 건다. 여기에도 Padé 는 필요 없다.
"""
